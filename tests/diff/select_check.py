"""Certified selection under a budget (Stage 21a4; PHASE2_SPEC.md §A.6 amendment (8), refinement
(8′)): `cqr certify --budget w,d,t,a --prefer width|depth|t|anc`.

  * the committed examples/certs/grover_pred_037_sel is regenerated (`--budget 12,200,100,8
    --prefer depth --report`): certified; Cert.lean, .qir, .qasm byte-identical to the committed
    directory and the JSON equal outside reference_configuration; the selected candidate is
    fewLogMbu (depth alone would pick treeMbu, whose w = 15 exceeds 12); the three candidate grades
    equal the grades of the committed grover_pred_037, grover_pred_037_coh and grover_pred_037_few
    certificates; .qir / .qasm byte-identical to grover_pred_037_few's; Cert.lean with the selection
    block removed byte-identical to grover_pred_037_few/Cert.lean;
  * a second run, `--budget 20,300,200,8 --prefer depth`: certified, treeMbu selected, .qir / .qasm
    byte-identical to grover_pred_037's, Cert.lean minus the block = grover_pred_037/Cert.lean;
  * for both runs the semantic rules the schema cannot express: `admissible` = grade ≤ budget,
    `order` starts with the preferred letter, `selected` = the least admissible candidate (ties by
    list order), against Python's own argmin;
  * no fit (`--budget 9,300,300,9`): exit 1, code budget_unsatisfiable, the three grades in the
    message, nothing written; the refusals of G3: exit 2, nothing written;
  * two negative kernel tests through `CertifyTool audit` on mutated copies of the committed
    Cert.lean: (h1) budget raised to ⟨15, 200, 100, 8⟩ — chosen_fits still holds, `selected` fails
    (treeMbu is admissible with d = 134 < 172); (h2) the grade in cand_grade_treeCoherent lowered by
    one — the kernel check fails.

Usage: python -I tests/diff/select_check.py --cqr <path to cqr>   (after `lake build`)
"""

import argparse
import json
import os
import re
import shutil
import sys
import tempfile
import time

import jsonschema

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import certify_check as cc  # noqa: E402
import reparse_qasm  # noqa: E402
import reparse_qir  # noqa: E402

ROOT = cc.ROOT
SRC = os.path.join("examples", f"{cc.NAME}.cqr")
EXAMPLE_SEL = os.path.join(ROOT, "examples", "certs", "grover_pred_037_sel")
SEL_THEOREM = "CQRV.Cert.grover_pred_037.selected"
FITS_THEOREM = "CQRV.Cert.grover_pred_037.chosen_fits"
CANDS = [("treeMbu", "tree", "mbu"), ("treeCoherent", "tree", "coherent"), ("fewLogMbu", "few:log", "mbu")]
LETTER = {"width": "w", "depth": "d", "t": "t", "anc": "a"}
BLOCK = re.compile(r"/-! ## Certified selection \(PHASE2_SPEC §A\.6 \(8\), \(8′\)\) — generated by "
                   r"`cqr certify --budget [0-9,]+ --prefer [a-z]+` -/\n.*?#print axioms selected\n\n", re.S)


def grade_of(d):
    return json.loads(cc.read(os.path.join(d, "certificate.json")))["grade"]


def key(order, g):
    return [g[c] for c in order]


def argmin(cands, budget, order):
    adm = [(i, c) for i, c in enumerate(cands)
           if c["grade"] is not None and all(c["grade"][k] <= budget[k] for k in "wdta")]
    if not adm:
        return None
    return min(adm, key=lambda ic: (key(order, ic[1]["grade"]), ic[0]))[1]


def check_sel_dir(d, validator, budget, prefer, expect):
    """Schema 1.12.0 (1.11.0 before R5), the selection object and its semantic rules, the hash link and the emitted
    files of one selection directory; returns (cert, text)."""
    cert = json.loads(cc.read(os.path.join(d, "certificate.json")))
    validator.validate(cert)
    assert cert["schema_version"] == "1.12.0" and cert["grade_kind"] == "measured", cert["schema_version"]
    assert cert["pattern"] == "Grover" and "blocks" not in cert
    sel = cert["selection"]
    assert sel["budget"] == budget and sel["prefer"] == prefer, sel
    order = sel["order"]
    assert len(order) == 4 and sorted(order) == ["a", "d", "t", "w"] and order[0] == LETTER[prefer], order
    assert [(c["shape"], c["uncompute"]) for c in sel["candidates"]] == [(s, m) for _, s, m in CANDS], sel
    committed = [grade_of(cc.EXAMPLE), grade_of(cc.EXAMPLE_COH), grade_of(cc.EXAMPLE_FEW)]
    assert [c["grade"] for c in sel["candidates"]] == committed, "candidate grades = the committed certificates'"
    for c in sel["candidates"]:
        assert c["admissible"] == all(c["grade"][k] <= budget[k] for k in "wdta"), c
    best = argmin(sel["candidates"], budget, order)
    assert best is not None and sel["selected"] == {"shape": best["shape"], "uncompute": best["uncompute"]}, sel
    name = [n for n, s, m in CANDS if (s, m) == (sel["selected"]["shape"], sel["selected"]["uncompute"])][0]
    assert name == expect, (name, expect)
    assert sel["theorem"] == SEL_THEOREM
    assert cert["grade"] == best["grade"] and all(cert["grade"][k] <= budget[k] for k in "wdta")
    assert cert["status"] == "certified" and cert["obligations"] == [] and cert["axioms"] == cc.STANDARD
    assert cert["theorem"] == cc.THEOREM and cert["uncompute"] == sel["selected"]["uncompute"]
    assert cert.get("diffusion_shape", "tree") == sel["selected"]["shape"]
    text = cc.read(os.path.join(d, "Cert.lean"))
    circ = cc.emitted_circuit(text)
    assert cert["hashes"]["circuit"] == cc.sha3(cc.canon(circ).encode("utf-8")), "circuit hash"
    assert cert["hashes"]["proof"] == cc.proof_hash(text), "proof hash"
    for fmt, mod in (("qasm", reparse_qasm), ("qir", reparse_qir)):
        parsed, terminal = mod.parse(cc.read(os.path.join(d, f"{cc.NAME}.{fmt}")))
        assert parsed == circ and len(terminal) == circ["n_data"], fmt
    # the selection block
    b = budget
    frags = [f"def budget : Grade := ⟨{b['w']}, {b['d']}, {b['t']}, {b['a']}⟩\n",
             "theorem chosen_fits : Synthesis.grade emitted ≤ budget := by\n  rw [grade_eq]\n  decide\n",
             "theorem selected : ∀ c ∈ Patterns.candidates, ∀ C, c.build net 8 2 = .ok C →\n",
             f"Patterns.Grade.key Patterns.Pref.{prefer} (Synthesis.grade C)",
             "#print axioms chosen_fits\n", "#print axioms selected\n",
             f"— generated by `cqr certify --budget {b['w']},{b['d']},{b['t']},{b['a']} --prefer {prefer}` -/"]
    for n, _, _ in CANDS:
        g = [c for c in sel["candidates"] if (c["shape"], c["uncompute"]) == [(s, m) for nn, s, m in CANDS if nn == n][0]][0]["grade"]
        lit = f"⟨{g['w']}, {g['d']}, {g['t']}, {g['a']}⟩"
        frags.append(f"theorem cand_grade_{n} : Synthesis.grade <$> Patterns.Candidate.{n}.build net 8 2 = .ok {lit}")
        if n == expect:
            frags.append(f"theorem cand_grade_{n} : Synthesis.grade <$> Patterns.Candidate.{n}.build net 8 2 = .ok {lit} := by\n"
                         "  show Synthesis.grade <$> ")
    for frag in frags:
        assert text.count(frag) == 1, frag
    assert text.count("except_ok_of_check _ _ (by decide +kernel)") >= 2, "the two other candidates by decide +kernel"
    assert len(BLOCK.findall(text)) == 1 and "sorry" not in text and "native_decide" not in text
    return cert, text


def strip_block(text):
    stripped, n = BLOCK.subn("", text)
    assert n == 1, "exactly one selection block"
    return stripped


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("--cqr", required=True)
    args = ap.parse_args()
    validator = jsonschema.Draft202012Validator(json.loads(cc.read(cc.SCHEMA)))
    t_all = time.time()
    tmp = tempfile.mkdtemp(prefix="cqrv-select-")
    try:
        # the committed selection directory, regenerated
        out = os.path.join(tmp, "sel")
        t0 = time.time()
        rc, so, se = cc.certify(args.cqr, SRC, out, "--budget", "12,200,100,8", "--prefer", "depth", "--report")
        dt = time.time() - t0
        assert rc == 0, (rc, so, se)
        lines = so.rstrip("\n").split("\n")
        assert lines[-2] == "certified" and lines[-1] == ("selection: few:log + mbu (prefer depth; budget "
                                                         "(12, 200, 100, 8); 1 of 3 candidates admissible)"), lines[-2:]
        budget = {"w": 12, "d": 200, "t": 100, "a": 8}
        cert, text = check_sel_dir(out, validator, budget, "depth", "fewLogMbu")
        ex, _ = check_sel_dir(EXAMPLE_SEL, validator, budget, "depth", "fewLogMbu")
        for f in ("Cert.lean", f"{cc.NAME}.qir", f"{cc.NAME}.qasm"):
            assert cc.read(os.path.join(out, f), "rb") == cc.read(os.path.join(EXAMPLE_SEL, f), "rb"), \
                f"committed selection example differs: {f}"
        assert cc.without(cert, cc.MACHINE) == cc.without(ex, cc.MACHINE), "committed selection certificate.json"
        assert cc.masked(cc.read(os.path.join(out, "certificate.json"))) == \
            cc.masked(cc.read(os.path.join(EXAMPLE_SEL, "certificate.json"))), "selection certificate.json bytes"
        for f in (f"{cc.NAME}.qir", f"{cc.NAME}.qasm"):
            assert cc.read(os.path.join(out, f), "rb") == cc.read(os.path.join(cc.EXAMPLE_FEW, f), "rb"), \
                f"{f} differs from grover_pred_037_few"
        assert strip_block(text) == cc.read(os.path.join(cc.EXAMPLE_FEW, "Cert.lean")), \
            "Cert.lean minus the selection block differs from grover_pred_037_few/Cert.lean"
        kc = cert["reference_configuration"]["kernel_check"]
        print(f"ok:   --budget 12,200,100,8 --prefer depth: `certified` + the selection line (exit 0, {dt:.0f} s; "
              f"kernel {cc.secs(kc['kernel_ms'])}, wall {cc.secs(kc['wall_ms'])}); fewLogMbu selected (depth alone "
              "would pick treeMbu, w = 15 > 12); schema v1.12.0 with selection; the three candidate grades = the "
              "committed grover_pred_037 / _coh / _few grades; committed examples/certs/grover_pred_037_sel agrees "
              "(bytes; JSON outside reference_configuration)")
        print("ok:   .qir / .qasm byte-identical to grover_pred_037_few's; Cert.lean minus the selection block "
              "byte-identical to grover_pred_037_few/Cert.lean; chosen_fits, selected, cand_grade_* present; "
              "circuit and proof hashes recomputed; QASM / QIR re-parse")
        # the run report
        rep = json.loads(cc.read(os.path.join(out, "run_report.json")))
        md = cc.read(os.path.join(out, "run_report.md"))
        stages = [r["stage"] for r in rep["rows"]]
        assert stages[:9] == cc.STAGES and "4b. Certified selection" in stages, stages
        row = [r for r in rep["rows"] if r["stage"] == "4b. Certified selection"][0]
        assert "fewLogMbu (few:log + mbu): grade (10, 172, 96, 2), admissible" in row["resources"], row
        assert "treeMbu (tree + mbu): grade (15, 134, 72, 7), not admissible" in row["resources"], row
        assert row["verification"] == "kernel-checked" and "select_spec" in row["note"]
        assert "- selection: budget (12, 200, 100, 8), prefer depth → fewLogMbu (few:log + mbu); 1 of 3 candidates admissible" in md
        print("ok:   run report: row '4b. Certified selection' lists the three candidates with grades and "
              "admissibility and the choice; the header carries the selection line")
        # the second run: a generous budget, depth → treeMbu
        out2 = os.path.join(tmp, "sel2")
        t0 = time.time()
        rc, so, se = cc.certify(args.cqr, SRC, out2, "--budget", "20,300,200,8", "--prefer", "depth")
        dt2 = time.time() - t0
        assert rc == 0, (rc, so, se)
        lines = so.rstrip("\n").split("\n")
        assert lines[-2] == "certified" and lines[-1] == ("selection: tree + mbu (prefer depth; budget "
                                                         "(20, 300, 200, 8); 3 of 3 candidates admissible)"), lines[-2:]
        cert2, text2 = check_sel_dir(out2, validator, {"w": 20, "d": 300, "t": 200, "a": 8}, "depth", "treeMbu")
        for f in (f"{cc.NAME}.qir", f"{cc.NAME}.qasm"):
            assert cc.read(os.path.join(out2, f), "rb") == cc.read(os.path.join(cc.EXAMPLE, f), "rb"), \
                f"{f} differs from grover_pred_037"
        assert strip_block(text2) == cc.read(os.path.join(cc.EXAMPLE, "Cert.lean")), \
            "Cert.lean minus the selection block differs from grover_pred_037/Cert.lean"
        assert cert2["grade"] == {"w": 15, "d": 134, "t": 72, "a": 7} and "diffusion_shape" not in cert2
        print(f"ok:   --budget 20,300,200,8 --prefer depth: `certified`, treeMbu selected, 3 of 3 admissible "
              f"(exit 0, {dt2:.0f} s); .qir / .qasm byte-identical to grover_pred_037's; Cert.lean minus the block "
              "= grover_pred_037/Cert.lean; the semantic rules (admissible, order, argmin with ties by list "
              "order) hold for both runs")
        # no fit
        out3 = os.path.join(tmp, "nofit")
        rc, so, se = cc.certify(args.cqr, SRC, out3, "--budget", "9,300,300,9", "--prefer", "depth")
        d = json.loads(so.strip().split("\n")[-1])
        assert rc == 1 and d["code"] == "budget_unsatisfiable" and d["stage"] == "synthesize", (rc, so, se)
        for g in ("(15, 134, 72, 7)", "(15, 200, 144, 7)", "(10, 172, 96, 2)"):
            assert g in d["message"], (g, d["message"])
        assert not os.path.exists(out3), "a certificate was written although no candidate fits"
        print("ok:   --budget 9,300,300,9: budget_unsatisfiable (stage synthesize) listing the three grades, "
              "exit 1, nothing written")
        # the refusals of G3
        for label, extra in (("--budget without --prefer", ["--budget", "12,200,100,8"]),
                             ("--prefer without --budget", ["--prefer", "depth"]),
                             ("three components", ["--budget", "12,200,100", "--prefer", "depth"]),
                             ("non-numeric budget", ["--budget", "12,200,x,8", "--prefer", "depth"]),
                             ("negative component", ["--budget", "12,-200,100,8", "--prefer", "depth"]),
                             ("unknown preference", ["--budget", "12,200,100,8", "--prefer", "size"]),
                             ("with --shape", ["--budget", "12,200,100,8", "--prefer", "depth", "--shape", "few:log"]),
                             ("with --uncompute", ["--budget", "12,200,100,8", "--prefer", "depth", "--uncompute", "coherent"]),
                             ("with --problem count", ["--budget", "12,200,100,8", "--prefer", "depth", "--problem", "count", "--precision", "4"]),
                             ("repeated --budget", ["--budget", "12,200,100,8", "--budget", "12,200,100,8", "--prefer", "depth"])):
            out4 = os.path.join(tmp, "refused")
            rc, so, se = cc.certify(args.cqr, SRC, out4, *extra)
            assert rc == 2 and not os.path.exists(out4), (label, rc, so, se)
        print("ok:   refused with exit 2, nothing written: --budget without --prefer, --prefer without --budget, a "
              "budget that is not four naturals, an unknown preference, --budget with --shape / --uncompute / "
              "--problem count, a repeated flag")
        # negative kernel tests on mutated copies of the committed Cert.lean
        base = cc.read(os.path.join(EXAMPLE_SEL, "Cert.lean"))
        bud = "def budget : Grade := ⟨12, 200, 100, 8⟩\n"
        cg = "theorem cand_grade_treeCoherent : Synthesis.grade <$> Patterns.Candidate.treeCoherent.build net 8 2 = .ok ⟨15, 200, 144, 7⟩"
        assert base.count(bud) == 1 and base.count(cg) == 1
        for label, mutated in (("(h1) budget raised to ⟨15, 200, 100, 8⟩: chosen_fits holds, `selected` fails "
                                "(treeMbu admissible with d = 134 < 172)", base.replace(bud, bud.replace("12", "15"))),
                               ("(h2) the grade in cand_grade_treeCoherent lowered by one (199)",
                                base.replace(cg, cg.replace("⟨15, 200, 144, 7⟩", "⟨15, 199, 144, 7⟩")))):
            d = os.path.join(tmp, "mut")
            os.makedirs(d, exist_ok=True)
            path = os.path.join(d, "Cert.lean")
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(mutated)
            t0 = time.time()
            rc, so, se = cc.run(["lake", "env", "lean", "--run", os.path.join("scripts", "CertifyTool.lean"),
                                 "audit", path, cc.THEOREM, FITS_THEOREM, SEL_THEOREM])
            assert rc == 1 and ": pass" not in so and "certified" not in so, (label, rc, so[-600:], se[-600:])
            print(f"ok:   {label}: the kernel check fails (exit 1, {time.time() - t0:.0f} s)")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print(f"select_check: all checks passed ({time.time() - t_all:.0f} s)")


if __name__ == "__main__":
    main()
