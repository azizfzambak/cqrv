"""Stage 19b B6 (docs/tasks/STAGE19_TASK.md; PHASE2_SPEC.md §A.3, the compositional certificate
form) — the block probe of the counting circuit. Report only: no certificate, not in CI.

For grover_pred_037 (n = 8, M = 32), m = 4, shape tree, both uncomputation modes:
  1. `scripts/CertifyTool.lean counting-sample examples/grover_pred_037.cqr 4 --uncompute <mode>
     --lean bench/counting/Blocks_<mode>.lean` prints the block table (every distinct block once
     with its multiplicity, grade, GradeExt, liveEnd) and writes the Lean file that states each
     distinct block as a literal with its `… = .ok block` link (as `emitted_ok`) and its
     `grade_eq` / `gradeExt_eq` by `decide +kernel`;
  2. that file is measured per declaration with the Stage 18a machinery (`scripts/kernel_forms.py
     profile`: a copy with `#print axioms <name>` after every declaration, `lean -DElab.async=false
     -Dprofiler=true`, 900 s timeout, a `lean` process above 8 GB is killed; one Lean process at a
     time; the peak working set is that of the whole run);
  3. docs/benchmarks/COUNTING_BLOCKS.md is written from the results (`bench/counting/out/state.json`).

Stop conditions (PHASE2_SPEC §A.3 item 4): a block above 600 gates, or a `grade_eq` above 30 s —
the report marks them; the task text says to stop and ask.

Usage (after `lake build`, from the repository root, in your own terminal; LEAN_NUM_THREADS=4):
    scripts/counting_blocks.sh [--timeout 900] [--threshold-ms 100] [--mem-kill-mb 8000]
                               [--report-only]
"""

import argparse
import json
import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
sys.path.insert(0, os.path.join(ROOT, "tests", "diff"))
import kernel_forms  # noqa: E402
from kernel_forms import profile, read, write, log  # noqa: E402
from bench_scaling import machine, toolchain  # noqa: E402
from lean_tool import certify_tool  # noqa: E402

OUT = os.path.join(ROOT, "bench", "counting", "out")
STATE = os.path.join(OUT, "state.json")
MD = os.path.join(ROOT, "docs", "benchmarks", "COUNTING_BLOCKS.md")
SRC = os.path.join("examples", "grover_pred_037.cqr")
M = 4
MODES = ["mbu", "coherent"]
GATE_LIMIT = 600
GRADE_EQ_LIMIT_S = 30.0


def load_state():
    if os.path.exists(STATE):
        return json.load(open(STATE, encoding="utf-8"))
    return {}


def save_state(st):
    os.makedirs(OUT, exist_ok=True)
    write(STATE, json.dumps(st, indent=1, ensure_ascii=False))


def fmt_s(v):
    return "—" if v is None else f"{v:.2f}"


def g4(g):
    return f"({g['w']}, {g['d']}, {g['t']}, {g['a']})"


def e5(e):
    return f"({e['two_qubit']}, {e['t_depth']}, {e['rot']}, {e['meas']}, {e['ff']})"


def probe(args, st):
    for mode in MODES:
        if mode in st and st[mode].get("profile") and not args.redo:
            log(f"{mode}: done, skipped")
            continue
        lean_file = os.path.join(ROOT, "bench", "counting", f"Blocks_{mode}.lean")
        log(f"counting-sample {SRC} m = {M} --uncompute {mode} --lean {os.path.relpath(lean_file, ROOT)}")
        out = certify_tool(["counting-sample", SRC, str(M), "--shape", "tree", "--uncompute", mode,
                            "--lean", os.path.relpath(lean_file, ROOT)])
        obj = json.loads(out)
        table = [{k: v for k, v in row.items() if k != "circuit"} for row in obj["blocks"]]
        rec = {"table": table, "measured": obj["measured"], "composed": obj["composed"],
               "n": obj["n"], "m": obj["m"],
               "lean_file": os.path.relpath(lean_file, ROOT).replace(os.sep, "/"),
               "when": time.strftime("%Y-%m-%d %H:%M:%S")}
        st[mode] = rec
        save_state(st)
        rec["profile"] = profile(lean_file, args.timeout, args.threshold_ms, f"Blocks_{mode}")
        save_state(st)


def report(st):
    meta = st.get("meta", {})
    L = []
    L.append("# The counting circuit's blocks (Stage 19b B6)\n")
    L.append("PHASE2_SPEC.md §A.3 (the compositional certificate form, decided at the 18a review; "
             "item 4: a block above 600 instructions or a `grade_eq` above 30 s reopens the "
             "kernel-friendly evaluator); docs/tasks/STAGE19_TASK.md B6; report §9.5.1 (measured "
             "values only). Generated by `scripts/counting_blocks.py` from "
             "`bench/counting/out/state.json` (`bench/counting/` is git-ignored: the generated "
             "`Blocks_<mode>.lean`, the marked copies and the Lean logs are reproducible from the "
             "command below, as `bench/forms/out/` in Stage 18a). Report only: no certificate.\n")
    L.append("## Method\n")
    L.append(f"- Instance: `examples/grover_pred_037.cqr` (n = 8, M = 32), m = {M} (15 controlled "
             "iterates), shape tree, both uncomputation modes; the circuit of `countingCircuit` "
             "(PHASE2_SPEC §A.3 amendment (4)).")
    L.append(f"- Machine: {meta.get('machine', '?')}; `LEAN_NUM_THREADS={meta.get('lean_threads', '?')}`; "
             f"run {meta.get('when', '?')}.")
    L.append(f"- Toolchain: {meta.get('toolchain', '?')}.")
    L.append("- The block table is `scripts/CertifyTool.lean counting-sample`; every distinct block "
             "appears once with its multiplicity (the `2^j` copies of controlled iterate `j` are one "
             "literal). The Lean files `bench/counting/Blocks_<mode>.lean` state each block as a "
             "literal with its link to the builder (`… = .ok block`, as `emitted_ok`) and its "
             "`grade_eq` / `gradeExt_eq` by `decide +kernel`.")
    L.append("- Per declaration: the Stage 18a machinery (`scripts/kernel_forms.py profile`): a copy "
             "with `#print axioms <name>` after every declaration, `lean -DElab.async=false "
             "-Dprofiler=true -Dprofiler.threshold=T`; the profiler's `… took` lines between two "
             "markers belong to the declaration the second marker names; `type checking` is the "
             "kernel; lines below the threshold are not printed (`—`). Timeout 900 s; a `lean` "
             "process above 8 GB is killed (`mem-kill`). Peak MB is the peak working set of the "
             "whole Lean run, not of one declaration.")
    L.append("- The whole circuit's measured grade is the compiled evaluation (`Circuit.grade`), "
             "not the kernel's; the composed bound is `⊕` with the multiplicities (Stage 19a, "
             "`grade_foldl_append_le` / `grade_replicate_le`; `tDepth` as `tDepth(init) + Σ tCount`).\n")
    stops = []
    for mode in MODES:
        rec = st.get(mode)
        if not rec:
            continue
        prof = rec.get("profile") or {}
        decls = prof.get("decls", {})
        L.append(f"## Mode `{mode}`\n")
        L.append(f"Profile outcome: {prof.get('outcome', '—')}; cumulative kernel `type checking` "
                 f"{fmt_s(prof.get('kernel_s'))} s; wall {fmt_s(prof.get('wall_s'))} s; peak "
                 f"{prof.get('peak_mb', '—')} MB; file `{rec['lean_file'].replace(os.sep, '/')}`"
                 + (f"; first error: {prof['error']}" if prof.get("error") else "") + ".\n")
        L.append("| block | gates | multiplicity | grade (w, d, t, a) | GradeExt (2q, tDepth, rot, meas, ff) | liveEnd | bits | ancillae | `_ok` s | `grade_eq` s | `gradeExt_eq` s |")
        L.append("|---|---|---|---|---|---|---|---|---|---|---|")
        for row in rec["table"]:
            nm = row["name"]
            def tc(suffix):
                d = decls.get(f"{nm}{suffix}", {})
                return d.get("type checking")
            ok_s, ge_s, gx_s = tc("_ok"), tc("_grade_eq"), tc("_gradeExt_eq")
            flag = ""
            if row["length"] > GATE_LIMIT:
                flag += " **> 600 gates**"
                stops.append(f"{mode}/{nm}: {row['length']} gates")
            if ge_s is not None and ge_s > GRADE_EQ_LIMIT_S:
                flag += " **grade_eq > 30 s**"
                stops.append(f"{mode}/{nm}: grade_eq {ge_s:.1f} s")
            L.append(f"| `{nm}`{flag} | {row['length']} | {row['multiplicity']} | {g4(row['grade'])} | "
                     f"{e5(row['grade_ext'])} | {row['live_end']} | {row['n_bits']} | {row['n_anc']} | "
                     f"{fmt_s(ok_s)} | {fmt_s(ge_s)} | {fmt_s(gx_s)} |")
        me, co = rec["measured"], rec["composed"]
        L.append("")
        L.append(f"Whole circuit: {me['gates']} gates, {me['n_bits']} classical bits, {me['n_anc']} "
                 f"ancillae; measured grade {g4(me['grade'])} (compiled), composed bound "
                 f"{g4(co['grade'])}; measured GradeExt {e5(me['grade_ext'])}, composed "
                 f"{e5(co['grade_ext'])} (tDepth a bound).\n")
        if decls:
            L.append("Per declaration (seconds; `—` below the threshold):\n")
            L.append("| declaration | type checking s | elaboration s | other |")
            L.append("|---|---|---|---|")
            for name in prof.get("order", []):
                d = decls.get(name, {})
                other = ", ".join(f"{k} {v:.2f}" for k, v in d.items()
                                  if k not in ("type checking", "elaboration"))
                L.append(f"| `{name}` | {fmt_s(d.get('type checking'))} | {fmt_s(d.get('elaboration'))} | {other or '—'} |")
            L.append("")
    L.append("## Stop conditions (PHASE2_SPEC §A.3 item 4)\n")
    if stops:
        L.append("**STOP**: " + "; ".join(stops) + ".")
    else:
        L.append("None: every block is below 600 gates and every `grade_eq` below 30 s.")
    L.append("")
    write(MD, "\n".join(L))
    log(f"wrote {os.path.relpath(MD, ROOT)}")
    if stops:
        log("STOP conditions: " + "; ".join(stops))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--timeout", type=int, default=900)
    ap.add_argument("--threshold-ms", type=int, default=100)
    ap.add_argument("--mem-kill-mb", type=int, default=8000)
    ap.add_argument("--report-only", action="store_true")
    ap.add_argument("--redo", action="store_true")
    args = ap.parse_args()
    kernel_forms.MEM_KILL_MB = args.mem_kill_mb
    st = load_state()
    if not args.report_only:
        st["meta"] = {"machine": machine(), "toolchain": toolchain(),
                      "lean_threads": os.environ.get("LEAN_NUM_THREADS", "unset"),
                      "when": time.strftime("%Y-%m-%d %H:%M:%S")}
        save_state(st)
        probe(args, st)
    report(st)


if __name__ == "__main__":
    main()
